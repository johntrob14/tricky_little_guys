"""Length-adjusted Astra strict passes (meta allowed) of the length-trained models vs base gpt-oss-120b at each reasoning level.

What CoT length alone predicts is modelled on base only, two ways:
  logistic  thinkvec/lenadj.py: strict ~ constraint intercept + log2(CoT words + 1), fit on base's 324 Astra rows (low, medium and
            high pooled).
  bins      base's pass rate per (constraint, CoT-token bin) on the full CoT-Control default protocol (results/full_compare/
            full_lenbins.csv: 10,836 rows, medium, temperature 0, bins <100 / 100-199 / 200-399 / 400-799 / 800-1599 / 1600+),
            looked up by each row's constraint and CoT tokens (gpt-oss tokenizer, as full_compare.py).
Adjusted passes of a model at a level = observed - (sum of predicted pass over its 108 rows - the same sum over base's rows at that
level): the change its length distribution alone predicts is removed, so base's adjusted count is its observed count.
95% CIs: bootstrap draws of the 108 items, paired across models and levels; the logistic is refit on each draw, the bin rates are fixed.

    .venv/bin/python astra_lenadj.py --out ../results/astra_levels --chart ../../../figures/astra_len2_lenadj.png
"""

import argparse
import json
import sys
from pathlib import Path

import matplotlib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from transformers import AutoTokenizer

from astra_levels import LEVELS, MODELS, adjusted, bootstrap, frame, load
from full_compare import BINS, LABELS

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "thinkvec"))
from lenadj import add_length_adjustment  # noqa: E402

matplotlib.use("Agg")
LENBINS = Path(__file__).parent.parent / "results/full_compare/full_lenbins.csv"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--chart", type=Path, required=True)
    ap.add_argument("--draws", type=int, default=2000)
    args = ap.parse_args()
    tok = AutoTokenizer.from_pretrained("openai/gpt-oss-120b")
    df = frame({m: {e: load(run) for e, run in lv.items()} for m, lv in MODELS.items()})
    df["cot_tokens"] = [len(tok.encode(t, add_special_tokens=False)) for t in df.reasoning]
    lb = pd.read_csv(LENBINS).query("model == 'Base gpt-oss-120b'")
    rate = {(c, b): p for c, b, p in zip(lb.constraint, lb.bin, lb["pass"])}
    df["p_bin"] = [rate[c, b] for c, b in zip(df.constraint, pd.cut(df.cot_tokens, BINS, labels=LABELS, right=False))]
    odds = add_length_adjustment(df, "base")
    point = adjusted(df)
    boot, boot_odds = bootstrap(df, args.draws)
    ci = lambda f: tuple(np.percentile([f(b) for b in boot], [2.5, 97.5]))

    res = {}
    for (m, e), p in point.items():
        res[f"{m}|{e}"] = dict(p, **{f"{k}_gain_ci": ci(lambda b, k=k: b[m, e][k] - b[m, e]["base"]) for k in ("observed", "logistic", "bins")},
                              **{f"{k}_ci": ci(lambda b, k=k: b[m, e][k]) for k in ("observed", "logistic", "bins")})
    (args.out / "lenadj.json").write_text(json.dumps(dict(odds_per_doubling=odds, odds_ci=list(np.percentile(boot_odds, [2.5, 97.5])), draws=args.draws, cells=res), indent=1))

    md = [f"# Length-adjusted Astra strict passes (meta allowed), of 108\n\nGenerated by `rl/astra_lenadj.py` (method in its docstring). "
          f"Logistic fit on base: odds of a pass x{odds:.2f} per doubling of CoT words [95% CI {np.percentile(boot_odds, 2.5):.2f}, "
          f"{np.percentile(boot_odds, 97.5):.2f}]. Cells: passes (gain over base at the same level [95% bootstrap CI over items]). "
          f"Predicted = passes base's length model expects from the model's CoT lengths.\n"]
    gain = lambda r, k: f"{r[k]:.1f} ({r[k] - r['base']:+.1f} [{r[k + '_gain_ci'][0]:+.1f}, {r[k + '_gain_ci'][1]:+.1f}])"
    for e in LEVELS:
        md += [f"## {e}\n", "| model | observed | predicted (logistic) | adjusted (logistic) | predicted (bins) | adjusted (bins) | median CoT words | median CoT tokens |",
               "|---|---|---|---|---|---|---|---|"]
        for m in MODELS:
            r, g = res[f"{m}|{e}"], df[(df.condition == m) & (df.level == e)]
            md.append(f"| {m} | {gain(r, 'observed')} | {r['pred_logistic']:.1f} | {gain(r, 'logistic')} | {r['pred_bins']:.1f} | {gain(r, 'bins')} | "
                      f"{g.cot_words.median():.0f} | {g.cot_tokens.median():.0f} |")
        md.append("")
    md += ["## len2 vs base per constraint (of 12): observed passes, predicted by bins, low / medium / high\n",
           "| constraint | base observed | base predicted (bins) | len2 observed | len2 predicted (bins) |", "|---|---|---|---|---|"]
    for c in sorted(df.constraint.unique()):
        cell = lambda m, col, fmt: " / ".join(fmt(df[(df.condition == m) & (df.level == e) & (df.constraint == c)][col].sum()) for e in LEVELS)
        md.append(f"| {c} | {cell('base', 'strict', str)} | {cell('base', 'p_bin', '{:.1f}'.format)} | {cell('len2', 'strict', str)} | "
                  f"{cell('len2', 'p_bin', '{:.1f}'.format)} |")
    (args.out / "lenadj.md").write_text("\n".join(md) + "\n")

    plt.rcParams.update({"figure.facecolor": "#1a1a19", "axes.facecolor": "#1a1a19", "text.color": "#f0efec", "axes.labelcolor": "#c3c2b7",
                         "xtick.color": "#c3c2b7", "ytick.color": "#c3c2b7", "axes.edgecolor": "#55554f"})
    bars = [("base, observed", "base", "observed", "#8a8a83"), ("len2, observed", "len2", "observed", "#3987e5"),
            ("len2, length-adjusted (logistic on base Astra rows)", "len2", "logistic", "#d95926"),
            ("len2, length-adjusted (base full-protocol bins)", "len2", "bins", "#199e70")]
    fig, ax = plt.subplots(figsize=(10, 5.5))
    w = 0.2
    for i, (label, m, k, color) in enumerate(bars):
        x = np.arange(len(LEVELS)) + (i - 1.5) * w
        y = [res[f"{m}|{e}"][k] for e in LEVELS]
        lo, hi = zip(*[res[f"{m}|{e}"][k + "_ci"] for e in LEVELS])
        ax.bar(x, y, w * 0.92, color=color, label=label)
        ax.errorbar(x, y, yerr=[np.array(y) - lo, np.array(hi) - y], fmt="none", ecolor="#f0efec", elinewidth=1, capsize=3)
        for xi, yi, top in zip(x, y, hi):
            ax.text(xi, top + 0.6, f"{yi:.0f}", ha="center", va="bottom", fontsize=9, color="#f0efec")
    ax.set_xticks(range(len(LEVELS)), [f"{e} effort" for e in LEVELS])
    ax.set_ylabel("Astra strict passes, meta allowed (of 108)")
    ax.set_title("gpt-oss-120b len2 step 60 vs base on Astra, raw and length-adjusted\n95% bootstrap CIs over items", fontsize=11)
    ax.grid(axis="y", color="#33332f", lw=0.6)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.legend(frameon=False, fontsize=9, labelcolor="#f0efec")
    fig.tight_layout()
    fig.savefig(args.chart, dpi=150)


if __name__ == "__main__":
    main()
